// ==========================================
// PresetRandomiser.h
// 「音楽的な」ランダマイズ
//
// 一様乱数を全パラメータにばら撒くと、ほぼ確実に使えない音になる
// （4 本とも同じ帯域で潰し合う／レゾナンス発振／LFO が速すぎる 等）。
// ここでは次の 4 つの制約を入れて、当たりの確率を上げている。
//
//  1. キャラクターを 1 つ選ぶ
//     モデルを 28 種から独立に選ぶのではなく、相性のよい 4 本組
//     （アナログ系／レゾナント系／デジタル系 …）をまとめて選ぶ。
//
//  2. 帯域を分担させる
//     4 本のカットオフを低→高の順にばらけさせ、同じ場所で
//     重ならないようにする。全部同じ帯域だと音が痩せる。
//
//  3. レゾナンスは本数で上限を変える
//     有効フィルターが多いほど 1 本あたりのレゾナンスを抑える。
//     4 本全部が高 Q だと合成後に破綻するため。
//
//  4. LFO はテンポ同期を基本にする
//     フリーランの速い LFO は不快になりやすいので、同期を優先し、
//     刻みも実用的な範囲（2小節〜16分）に限定する。
//
// メッセージスレッド専用（setValueNotifyingHost を使う）。
// ==========================================
#pragma once

#include <juce_audio_processors/juce_audio_processors.h>

class QuadMorphFilterAudioProcessor;

namespace PresetRandomiser
{
    /** 全体をランダム化する。seed を渡すと再現可能。 */
    void randomise(QuadMorphFilterAudioProcessor& proc, juce::Random& rng);
}
